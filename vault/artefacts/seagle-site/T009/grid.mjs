import { chromium } from "/home/jdrac/Documents/Workspace/seagle-website/node_modules/playwright/index.mjs"
const b = await chromium.launch({ args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] })
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } })
await ctx.addInitScript(() => { localStorage.setItem("seagle-theme","dark"); localStorage.setItem("i18nextLng","fr") })
const p = await ctx.newPage()
await p.goto("http://localhost:4404/lab", { waitUntil: "networkidle" })
await p.locator('a[href="/la-joconde"]').scrollIntoViewIfNeeded()
await p.waitForTimeout(1500)
await p.screenshot({ path: "lab-fr-dark-cards.png" })
console.log(await p.locator('section a[href="/la-joconde"]').isVisible())
await b.close()
