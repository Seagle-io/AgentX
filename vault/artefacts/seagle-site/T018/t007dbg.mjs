import { chromium } from "/home/jdrac/Documents/Workspace/seagle-website/node_modules/playwright/index.mjs"
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on("pageerror", e => console.log("PAGEERROR", e.message))
page.on("framenavigated", f => { if (f === page.mainFrame()) console.log("NAV", f.url()) })
await page.goto("http://localhost:4173/agentx/"); await page.waitForTimeout(1500)
const tabs = page.locator('[role="tab"]')
console.log("tabs", await tabs.count(), await tabs.allTextContents())
await tabs.first().scrollIntoViewIfNeeded(); await page.waitForTimeout(1500)
console.log("before", await page.evaluate(() => [location.pathname, document.querySelectorAll("video").length, document.querySelectorAll('[role=tab]').length]))
await tabs.nth(1).click({ force: true }); await page.waitForTimeout(500)
console.log("after1", await page.evaluate(() => [location.pathname, document.querySelectorAll("video").length, document.querySelectorAll('[role=tab]').length, document.title]))
await page.waitForTimeout(2000)
console.log("after1+2s", await page.evaluate(() => [location.pathname, document.querySelectorAll("video").length, document.querySelectorAll('[role=tab]').length, document.getElementById("root").innerText.length]))
await browser.close()
